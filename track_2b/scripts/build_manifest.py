#!/usr/bin/env python3
"""Merge generated + ACT manifests into data/testset/manifest.jsonl and write STATS.md.

Usage (from track_2b/):  python -I scripts/build_manifest.py

Inputs : data/testset/generated/manifest_generated.jsonl   (scripts/generate_testset.py)
         data/testset/act/manifest_act.jsonl               (scripts/import_act.py)
Outputs: data/testset/manifest.jsonl, data/testset/STATS.md
"""
from __future__ import annotations

import hashlib
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
TESTSET = HERE.parent / "data" / "testset"
sys.path.insert(0, str(HERE / "testset_gen"))
import common  # noqa: E402

FIELDS = ["case_id", "criterion", "page_lang", "source", "act_rule", "split", "expected", "path",
          "target_selector", "notes", "rule", "trap", "alt_expected", "difficulty", "pages",
          "template_id", "surface_forms", "tags", "license"]
LICENSES = {"generated": "CDLA-Permissive-2.0", "act": "W3C-20150513"}   # SPDX ids
OUTS = ["failed", "passed", "cantTell", "inapplicable"]


def read_jsonl(p: Path) -> list[dict]:
    if not p.exists():
        return []
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()]


def normalise(r: dict) -> dict:
    out = {k: r.get(k) for k in FIELDS}
    if out["trap"] is None:
        out["trap"] = False
    if out["pages"] is None:
        out["pages"] = 1
    if out["template_id"] is None:      # ACT: one template per rule (cases of a rule share fixtures)
        out["template_id"] = f"act/{r.get('act_rule')}"
    out["surface_forms"] = list(out["surface_forms"] or [])
    out["tags"] = list(out["tags"] or [])
    out["license"] = LICENSES[out["source"]]
    return out


def table(headers, rows) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(headers))) + "|"]
    for r in rows:
        lines.append("| " + " | ".join(str(x) for x in r) + " |")
    return "\n".join(lines)


def stats_md(rows: list[dict], sha256: str = "") -> str:
    order = {c: i for i, c in enumerate(common.CRITERIA)}
    crits = sorted({r["criterion"] for r in rows}, key=lambda c: order.get(c, 99))
    gen = [r for r in rows if r["source"] == "generated"]
    act = [r for r in rows if r["source"] == "act"]
    out = ["# Evaluation set statistics", "",
           "_Generated by `scripts/build_manifest.py` from `manifest.jsonl` — do not edit by hand._", ""]
    c_src = Counter(r["source"] for r in rows)
    c_split = Counter((r["source"], r["split"]) for r in rows)
    out += [f"- **Total rows:** {len(rows)} (generated {c_src['generated']}, ACT {c_src['act']})",
            f"- **Split:** generated dev {c_split[('generated', 'dev')]} / test {c_split[('generated', 'test')]}; "
            f"ACT test {c_split[('act', 'test')]} (ACT is never used for development)",
            f"- **Criteria covered:** {len(crits)}",
            f"- **manifest.jsonl sha256:** `{sha256}`",
            f"- **Licences (per row):** " + ", ".join(f"`{k}` {v}" for k, v in sorted(Counter(r['license'] for r in rows).items())),
            f"- **Injection subset:** {sum(1 for r in gen if 'injection' in r['tags'])} generated cases "
            f"(dev {sum(1 for r in gen if 'injection' in r['tags'] and r['split'] == 'dev')}, "
            f"test {sum(1 for r in gen if 'injection' in r['tags'] and r['split'] == 'test')})",
            f"- **Distinct ACT test cases:** {len({r['path'] for r in act})} "
            "(an ACT case mapped to two in-scope criteria appears once per criterion)",
            ""]

    # Overall outcome mix for generated
    cg = Counter(r["expected"] for r in gen)
    ng = max(1, len(gen))
    traps = sum(1 for r in gen if r["trap"] and r["expected"] in ("passed", "inapplicable"))
    npass = cg["passed"] + cg["inapplicable"]
    out += ["## Generated cases: outcome mix", "",
            table(["expected", "n", "share"], [[o, cg[o], f"{100 * cg[o] / ng:.1f} %"] for o in OUTS]), "",
            f"Exception traps (labelled passed/inapplicable although they resemble a failure): "
            f"**{traps}** = {100 * traps / max(1, npass):.1f} % of passed+inapplicable.", ""]

    # criterion x expected x source
    hdr = ["criterion", "name"] + [f"gen {o}" for o in OUTS] + ["gen total", "traps"] + [f"ACT {o}" for o in OUTS] + ["ACT total", "all"]
    trs = []
    by = defaultdict(Counter)
    for r in rows:
        by[(r["criterion"], r["source"])][r["expected"]] += 1
    tot = Counter()
    for c in crits:
        g, a = by[(c, "generated")], by[(c, "act")]
        tr = sum(1 for r in gen if r["criterion"] == c and r["trap"])
        row = [c, common.CRITERIA.get(c, ("?",))[0]] + [g[o] for o in OUTS] + [sum(g.values()), tr] + [a[o] for o in OUTS] + [sum(a.values()), sum(g.values()) + sum(a.values())]
        trs.append(row)
        for i, v in enumerate(row[2:]):
            tot[i] += v
    trs.append(["**total**", ""] + [tot[i] for i in range(len(hdr) - 2)])
    out += ["## Criterion × expected outcome × source", "", table(hdr, trs), ""]

    # criterion x language (generated)
    langs = ["de", "fr", "it", "en", "rm"]
    by_l = defaultdict(Counter)
    for r in gen:
        by_l[r["criterion"]][r["page_lang"]] += 1
    lrows = [[c] + [by_l[c][l] for l in langs] + [sum(by_l[c].values())] for c in crits if by_l[c]]
    lt = Counter()
    for r in gen:
        lt[r["page_lang"]] += 1
    lrows.append(["**total**"] + [lt[l] for l in langs] + [len(gen)])
    out += ["## Generated cases: criterion × page language", "", table(["criterion"] + langs + ["total"], lrows), ""]

    # criterion x language x expected (generated)
    detail = defaultdict(Counter)
    for r in gen:
        detail[(r["criterion"], r["page_lang"])][r["expected"]] += 1
    drows = []
    for c in crits:
        for l in langs:
            d = detail.get((c, l))
            if d:
                drows.append([c, l] + [d[o] for o in OUTS] + [sum(d.values())])
    out += ["## Generated cases: criterion × language × expected", "",
            table(["criterion", "lang"] + OUTS + ["n"], drows), ""]

    # split
    srows = []
    sp = defaultdict(Counter)
    for r in rows:
        sp[r["criterion"]][(r["source"], r["split"])] += 1
    tpl = defaultdict(lambda: defaultdict(set))
    for r in gen:
        tpl[r["criterion"]][r["split"]].add(r["template_id"])
    for c in crits:
        t_all = tpl[c]["dev"] | tpl[c]["test"]
        shared = len(tpl[c]["dev"] & tpl[c]["test"])
        srows.append([c, sp[c][("generated", "dev")], sp[c][("generated", "test")], len(t_all),
                      len(tpl[c]["dev"]), len(tpl[c]["test"]), shared, sp[c][("act", "test")]])
    out += ["## Split by criterion (group split by template)", "",
            "Generated cases are split by template group (`template_id`): no template is in both splits.", "",
            table(["criterion", "generated dev", "generated test", "templates", "dev templates", "test templates",
                   "shared", "ACT test"], srows), ""]

    # difficulty
    dif = Counter(r["difficulty"] for r in gen)
    out += ["## Generated cases: difficulty", "",
            table(["difficulty", "n"], [[k, dif[k]] for k in ("easy", "medium", "hard")]), ""]

    # ACT rules
    if act:
        ar = defaultdict(Counter)
        for r in act:
            ar[(r["act_rule"], r["criterion"])][r["expected"]] += 1
        arows = [[k[0], k[1]] + [v[o] for o in ("failed", "passed", "inapplicable")] + [sum(v.values())]
                 for k, v in sorted(ar.items(), key=lambda kv: (order.get(kv[0][1], 99), kv[0][0]))]
        out += ["## ACT rules imported", "",
                table(["ACT rule", "criterion", "failed", "passed", "inapplicable", "n"], arows), ""]
    return "\n".join(out) + "\n"


def main(argv=None) -> int:
    gen = read_jsonl(TESTSET / "generated" / "manifest_generated.jsonl")
    act = read_jsonl(TESTSET / "act" / "manifest_act.jsonl")
    rows = [normalise(r) for r in gen + act]
    ids = Counter(r["case_id"] for r in rows)
    dups = [k for k, v in ids.items() if v > 1]
    if dups:
        print(f"!! duplicate case_ids: {dups[:10]}")
        return 1
    TESTSET.mkdir(parents=True, exist_ok=True)
    data = "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows).encode("utf-8")
    (TESTSET / "manifest.jsonl").write_bytes(data)
    sha = hashlib.sha256(data).hexdigest()
    (TESTSET / "STATS.md").write_text(stats_md(rows, sha), encoding="utf-8", newline="\n")
    print(f"manifest.jsonl: {len(rows)} rows (generated {len(gen)}, act {len(act)}); STATS.md written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
